public class elephant
{
    int weight;
    boolean hasTusks;
    String name;
    public elephant()
    {
        weight = 2000;
        hasTusks = false;
        name = "Dumbo";
    }
    public elephant(int weightIN, boolean hasTusksIN, String nameIN)
    {
        weight = weightIN;
        hasTusks = hasTusksIN;
        name = nameIN;
    }
}